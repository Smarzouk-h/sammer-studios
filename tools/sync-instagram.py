#!/usr/bin/env python3
"""Pull recent posts from @sammerstudios into the site's Instagram strip.

    export IG_TOKEN="your-long-lived-token"
    python3 tools/sync-instagram.py

Writes data/instagram.js. The home page shows a "Latest on Instagram" strip
when that file has posts in it and hides the section when it does not, so it is
safe to run or not run.

WHAT THIS CANNOT DO
-------------------
Instagram does not let a website read a public account without credentials.
Meta retired the old Basic Display API, so the only supported route is the
Instagram Graph API, which needs:

  1. Your account switched to Professional (Business or Creator). Free.
  2. That account linked to a Facebook Page.
  3. An app created at developers.facebook.com with the
     instagram_graph_user_media and instagram_graph_user_profile permissions.
  4. A long-lived access token, which expires every 60 days and has to be
     refreshed. Re-running this script refreshes it and prints the new one.

If that sounds like more admin than it is worth, the alternative is in the
README: a hosted embed widget that handles all of the above for you.

WHY THESE PHOTOGRAPHS DO NOT JOIN THE PORTFOLIO
-----------------------------------------------
Instagram re-compresses everything to about 1080px. That is fine for a feed
strip and much too small for the print shop, where files are 2400px. Synced
posts therefore live in their own strip and are never sold as prints. To put a
photograph in the portfolio properly, add the original through
tools/curation.py and tools/build_images.py.
"""
import json, os, sys, urllib.parse, urllib.request

TOKEN = os.environ.get("IG_TOKEN", "").strip()
LIMIT = int(os.environ.get("IG_LIMIT", "12"))
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "data", "instagram.js")
FIELDS = "id,caption,media_type,media_url,permalink,thumbnail_url,timestamp"


def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.load(r)


def write(posts):
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/sync-instagram.py. Safe to delete. */\n")
        f.write("window.INSTAGRAM_POSTS = ")
        json.dump(posts, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {len(posts)} posts -> data/instagram.js")


if not TOKEN:
    print(__doc__)
    print("No IG_TOKEN set. Writing an empty feed so the section stays hidden.")
    write([])
    sys.exit(0)

try:
    me = get("https://graph.instagram.com/me?" + urllib.parse.urlencode(
        {"fields": "id,username", "access_token": TOKEN}))
    print(f"authenticated as @{me.get('username', '?')}")

    media = get("https://graph.instagram.com/me/media?" + urllib.parse.urlencode(
        {"fields": FIELDS, "limit": LIMIT, "access_token": TOKEN}))

    posts = []
    for m in media.get("data", []):
        if m.get("media_type") == "VIDEO":
            img = m.get("thumbnail_url")
        else:
            img = m.get("media_url")
        if not img:
            continue
        caption = (m.get("caption") or "").strip().split("\n")[0][:120]
        posts.append({
            "id": m["id"], "img": img, "link": m.get("permalink", ""),
            "caption": caption, "when": (m.get("timestamp") or "")[:10],
            "video": m.get("media_type") == "VIDEO",
        })
    write(posts)

    # Refresh the token so the next 60 days are covered.
    fresh = get("https://graph.instagram.com/refresh_access_token?" +
                urllib.parse.urlencode({"grant_type": "ig_refresh_token",
                                        "access_token": TOKEN}))
    if fresh.get("access_token"):
        print("\nToken refreshed. Replace IG_TOKEN with this, good for "
              f"{fresh.get('expires_in', 0) // 86400} more days:\n")
        print(fresh["access_token"])

except Exception as e:
    print(f"Instagram sync failed: {e}", file=sys.stderr)
    print("Leaving the existing data/instagram.js untouched.", file=sys.stderr)
    sys.exit(1)
