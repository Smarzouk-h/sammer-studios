#!/usr/bin/env python3
"""Render only the curation entries whose slug is not yet in data/photos.json,
then rewrite photos.json / photos.js in CURATION order. Same pipeline as
tools/build_images.py (ImageMagick, stripped metadata, content-hash version).

    python3 tools/build_incremental.py --site . --source ~/Downloads/_photo-staging
"""
import argparse, base64, hashlib, json, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ap = argparse.ArgumentParser()
ap.add_argument("--site", required=True)
ap.add_argument("--source", required=True)
A = ap.parse_args()
OUT = A.site
SP = os.path.join(OUT, "tools")
sys.path.insert(0, SP)
from curation import CURATION, COLLECTIONS  # noqa: E402

THUMB_EDGE, FULL_EDGE = 1000, 2400
PHONES = ("iphone", "pixel", "galaxy", "samsung")
CAMERAS = {
    "ILCE-7M4": "Sony A7 IV",
    "Canon EOS DIGITAL REBEL XTi": "Canon Rebel XTi, 2006",
    "Canon EOS 5D": "Canon EOS 5D, 2005",
    "DC VARIO-SUMMILUX 1:1.7-2.8/10.9-34 ASPH.": "Leica D-Lux 8",
    "DCR-DVD650": "Sony Handycam",
}

idx_to_path = {}
for line in open(os.path.join(SP, "_source_index.txt")):
    i, p = line.rstrip("\n").split("\t")
    idx_to_path[int(i)] = os.path.join(A.source, p)


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd[:3])}...\n{r.stderr[:400]}")


def convert(src, dst, edge, quality):
    run(["magick", src, "-auto-orient", "-colorspace", "sRGB", "-resize", f"{edge}x{edge}>",
         "-strip", "-quality", str(quality), "-interlace", "Plane",
         "-sampling-factor", "4:2:0", dst])


def lqip(src, tmp):
    run(["magick", src, "-auto-orient", "-colorspace", "sRGB", "-resize", "24x",
         "-blur", "0x1.2", "-strip", "-quality", "40", tmp])
    with open(tmp, "rb") as f:
        return "data:image/jpeg;base64," + base64.b64encode(f.read()).decode()


def camera_of(path):
    try:
        from PIL import Image
        from PIL.ExifTags import TAGS
        ex = Image.open(path).getexif() or {}
        tags = {TAGS.get(k, k): v for k, v in ex.items()}
        return str(tags.get("Model") or "").strip()
    except Exception:
        return ""


def dims(path):
    r = subprocess.run(["magick", "identify", "-format", "%w %h", path],
                       capture_output=True, text=True, check=True)
    w, h = r.stdout.split()
    return int(w), int(h)


def build(entry):
    src_idx, slug, title, coll, loc, feat = entry
    src = idx_to_path[src_idx]
    convert(src, f"{OUT}/photos/thumb/{slug}.webp", THUMB_EDGE, 80)
    convert(src, f"{OUT}/photos/thumb/{slug}.jpg", THUMB_EDGE, 80)
    convert(src, f"{OUT}/photos/full/{slug}.webp", FULL_EDGE, 82)
    convert(src, f"{OUT}/photos/full/{slug}.jpg", FULL_EDGE, 84)
    w, h = dims(f"{OUT}/photos/full/{slug}.jpg")
    model = camera_of(src)
    with open(f"{OUT}/photos/full/{slug}.jpg", "rb") as fh:
        ver = hashlib.md5(fh.read()).hexdigest()[:8]
    tmp = f"{OUT}/tools/_lqip_{slug}.jpg"
    lq = lqip(src, tmp)
    os.remove(tmp)
    return {
        "slug": slug, "title": title, "collection": coll, "location": loc,
        "featured": feat, "w": w, "h": h,
        "camera": "" if any(k in model.lower() for k in PHONES) else CAMERAS.get(model, model),
        "v": ver,
        "orient": "square" if abs(w - h) / max(w, h) < 0.06 else ("landscape" if w > h else "portrait"),
        "lqip": lq,
    }


existing = json.load(open(f"{OUT}/data/photos.json"))
by_slug = {p["slug"]: p for p in existing["photos"]}
todo = [e for e in CURATION if e[1] not in by_slug]
print(f"{len(by_slug)} existing, {len(todo)} to render")
with ThreadPoolExecutor(6) as ex:
    for p in ex.map(build, todo):
        by_slug[p["slug"]] = p
        print("  rendered", p["slug"], p["w"], "x", p["h"], p["camera"])

# Keep metadata of existing entries in sync with curation (title, location, featured)
photos = []
for src_idx, slug, title, coll, loc, feat in CURATION:
    p = by_slug[slug]
    p.update({"title": title, "collection": coll, "location": loc, "featured": feat})
    photos.append(p)

data = {"collections": [{"id": k, **v} for k, v in COLLECTIONS.items()], "photos": photos}
with open(f"{OUT}/data/photos.json", "w") as f:
    json.dump(data, f, indent=1)
with open(f"{OUT}/data/photos.js", "w") as f:
    f.write("/* Generated by build_images.py - do not edit by hand. */\n")
    f.write("window.PHOTO_DATA = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")
from collections import Counter
print(f"wrote {len(photos)} photos")
print(" ", dict(Counter(p["collection"] for p in photos)))
